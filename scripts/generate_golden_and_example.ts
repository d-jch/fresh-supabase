async function targetExists(path: string): Promise<boolean> {
  try {
    await Deno.lstat(path);
    return true;
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return false;
    throw error;
  }
}

async function ensureEmptyDirectory(path: string): Promise<void> {
  if (!(await targetExists(path))) {
    await Deno.mkdir(path, { recursive: true });
    return;
  }
  const info = await Deno.lstat(path);
  if (!info.isDirectory) {
    throw new Error(`output target is not a directory: ${path}`);
  }
  for await (const entry of Deno.readDir(path)) {
    throw new Error(
      `output target is not empty (${entry.name}); generation refuses to overwrite committed evidence: ${path}`,
    );
  }
}

async function copyTreeContents(source: string, target: string): Promise<void> {
  const entries = [];
  for await (const entry of Deno.readDir(source)) entries.push(entry);
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const sourcePath = join(source, entry.name);
    const targetPath = join(target, entry.name);
    if (entry.isDirectory) {
      await Deno.mkdir(targetPath);
      await copyTreeContents(sourcePath, targetPath);
    } else if (entry.isFile) {
      await Deno.copyFile(sourcePath, targetPath);
    } else {
      throw new Error(`unexpected non-file fixture entry: ${sourcePath}`);
    }
  }
}

async function sha256(bytes: Uint8Array): Promise<string> {
  return new Uint8Array(
    await crypto.subtle.digest("SHA-256", Uint8Array.from(bytes)),
  ).toHex();
}

async function fileHashes(
  directory: string,
  ignoredTopLevel: ReadonlySet<string> = new Set(),
): Promise<Record<string, string>> {
  const hashes: Record<string, string> = {};
  const visit = async (current: string): Promise<void> => {
    const entries = [];
    for await (const entry of Deno.readDir(current)) entries.push(entry);
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      if (current === directory && ignoredTopLevel.has(entry.name)) continue;
      const target = join(current, entry.name);
      if (entry.isDirectory) {
        await visit(target);
      } else if (entry.isFile) {
        hashes[relative(directory, target).replaceAll("\\", "/")] =
          await sha256(
            await Deno.readFile(target),
          );
      } else {
        throw new Error(`unexpected non-file output entry: ${target}`);
      }
    }
  };
  await visit(directory);
  return hashes;
}

if (Deno.args.length !== 0) {
  throw new Error("golden and example generation takes no arguments");
}
if (Deno.version.deno !== DENO_VERSION) {
  throw new Error(
    `example generation requires Deno ${DENO_VERSION}; found ${Deno.version.deno}`,
  );
}

for (const output of outputs) {
  if (!(await targetExists(output.source))) {
    throw new Error(
      `required committed upstream fixture is missing: ${output.source}`,
    );
  }
  await ensureEmptyDirectory(output.target);
  await copyTreeContents(output.source, output.target);
  const plan = await createExecutablePlan(
    output.target,
    output.block,
    CLI_VERSION,
  );
  if (plan.installPlan.issues.length > 0) {
    throw new Error(
      `${output.name} preflight failed: ${
        JSON.stringify(plan.installPlan.issues)
      }`,
    );
  }
  const result = await executeInstallPlan(plan);
  if (!result.changed) {
    throw new Error(`${output.name} generation unexpectedly made no changes`);
  }
}

