const standaloneRoot = await Deno.makeTempDir({
  prefix: "fresh-supabase-example-lock-",
});
try {
  await copyTreeContents(exampleRoot, standaloneRoot);
  const standaloneInstall = await new Deno.Command(Deno.execPath(), {
    args: ["install", "--minimum-dependency-age=0"],
    cwd: standaloneRoot,
    stdout: "piped",
    stderr: "piped",
  }).output();
  if (!standaloneInstall.success) {
    const decoder = new TextDecoder();
    throw new Error(
      `standalone example lock generation failed:\n${
        decoder.decode(standaloneInstall.stdout)
      }${decoder.decode(standaloneInstall.stderr)}`,
    );
  }
  await Deno.copyFile(
    join(standaloneRoot, "deno.lock"),
    join(exampleRoot, "deno.lock"),
  );
} finally {
  await Deno.remove(standaloneRoot, { recursive: true });
}

